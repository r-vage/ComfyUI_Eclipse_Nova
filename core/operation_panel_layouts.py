# Values, bounds and processing stay owned by each operation's schema/engine.


def bar(key, label, choice=None, toggles=(), **options):
    return {"key": key, "label": label, "choice": choice, "toggles": list(toggles), **options}


def section(key, label, rows, **options):
    return {"key": key, "label": label, "rows": rows, **options}


